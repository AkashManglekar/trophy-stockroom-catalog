type ItemCtx = { ref: RefData; vendors: Vendor[]; families: Family[]; vcodes: VendorCode[] };
type Val = string | number | null | undefined;
export type FieldDef<T, C> = { key: string; label: string; get: (row: T, ctx: C) => Val };

const typeOf = (p: Product, ref: RefData) =>
  ref.types.find((t) => t.div === p.div && t.code === p.type);

