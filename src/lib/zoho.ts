export const normHeader = (h: string) =>
  String(h || "")
    .toLowerCase()
    .replace(/^cf\./, "")
    .replace(/[^a-z0-9]/g, "");
export const KINDS = {
  items: {
    label: "Items",
    fields: ITEM_FIELDS,
    defaults: ITEM_DEFAULT_HEADERS,
    alias: ITEM_ALIAS,
    where: "Items → Import Items, duplicate handling by SKU",
  },
  vendors: {
    label: "Vendors",
    fields: VENDOR_FIELDS,
    defaults: VENDOR_DEFAULT_HEADERS,
    alias: VENDOR_ALIAS,
    where: "Purchases → Vendors → Import Vendors, duplicate handling by Display Name",
  },
} as const;
export type Kind = keyof typeof KINDS;

export function headerKey(kind: Kind, header: string, overrides?: Record<string, string>) {
  return overrides?.[header] ?? KINDS[kind].alias[normHeader(header)] ?? "blank";
}
